// Writes src/lib/marketing-html-cache-build-id.ts for a Workers build.
// `pnpm cf:build` runs this, bundles the id into the worker, then `--reset`
// restores the empty file so a deploy-only id is not committed.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const target = resolve('src/lib/marketing-html-cache-build-id.ts');

const emptySource = `/**
 * Suffix for the marketing HTML cache key. Empty in git.
 *
 * \`pnpm cf:build\` overwrites this for the Workers bundle, then restores
 * this empty value. Dev and \`pnpm build\` leave it empty; the manual epoch
 * in marketing-html-cache.ts still applies.
 */
export const MARKETING_HTML_CACHE_BUILD_ID = '';
`;

function sanitize(value) {
  return String(value)
    .replace(/[^A-Za-z0-9._-]/g, '')
    .slice(0, 80);
}

function generatedId() {
  let sha = 'nogit';
  try {
    sha = execSync('git rev-parse --short=12 HEAD', {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    sha = 'nogit';
  }
  const stamp = new Date()
    .toISOString()
    .replace(/\.\d{3}Z$/, 'Z')
    .replace(/[:-]/g, '');
  return sanitize(`${sanitize(sha) || 'nogit'}-${stamp}`);
}

if (process.argv.includes('--reset')) {
  writeFileSync(target, emptySource);
  process.exit(0);
}

let id = sanitize(process.env.MARKETING_HTML_CACHE_BUILD_ID || '');
if (!id) id = generatedId();
if (!/^[A-Za-z0-9._-]{1,80}$/.test(id)) {
  console.error('marketing html cache build id is empty');
  process.exit(1);
}

const source = `/**
 * Generated by scripts/write-marketing-html-cache-build-id.mjs during cf:build.
 * Restored to an empty string afterwards. Do not commit a non-empty value.
 */
export const MARKETING_HTML_CACHE_BUILD_ID = ${JSON.stringify(id)};
`;

writeFileSync(target, source);
console.log(`marketing html cache build id: ${id}`);
